"""Write a Robot as URDF (ROS, Gazebo, MATLAB importrobot, Pinocchio, PyBullet...)."""

from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

import numpy as np

from robomodel import __version__
from robomodel.multibody.robot import Robot


def _f(x: float) -> str:
    return f"{x:.9g}"


def _v(v) -> str:
    return " ".join(_f(x) for x in v)


def write_urdf(robot: Robot, out_dir: str | Path, name: str | None = None) -> Path:
    out = Path(out_dir)
    (out / "meshes").mkdir(parents=True, exist_ok=True)
    name = name or getattr(robot, "name", "robot")
    lines = [
        '<?xml version="1.0"?>',
        f"<!-- Generated by robomodel {__version__}. Inertias from the CAD shape with the "
        "user's mass (uniform density). -->",
        f'<robot name="{escape(name)}">',
    ]
    for link in robot.links.values():
        i = link.inertia
        lines += [
            f'  <link name="{escape(link.name)}">',
            "    <inertial>",
            f'      <origin xyz="{_v(link.com)}" rpy="0 0 0"/>',
            f'      <mass value="{_f(link.mass)}"/>',
            f'      <inertia ixx="{_f(i[0, 0])}" ixy="{_f(i[0, 1])}" ixz="{_f(i[0, 2])}" '
            f'iyy="{_f(i[1, 1])}" iyz="{_f(i[1, 2])}" izz="{_f(i[2, 2])}"/>',
            "    </inertial>",
        ]
        if link.mesh is not None:
            mesh_file = out / "meshes" / f"{link.name}.stl"
            link.mesh.export(mesh_file)
            for tag in ("visual", "collision"):
                lines += [
                    f"    <{tag}>",
                    f'      <geometry><mesh filename="meshes/{link.name}.stl"/></geometry>',
                    f"    </{tag}>",
                ]
        lines.append("  </link>")
    if not robot.floating:  # a fixed robot is bolted to the world (Gazebo: does not fall)
        lines += [
            '  <link name="world"/>',
            '  <joint name="world_fixed" type="fixed">',
            '    <parent link="world"/>',
            f'    <child link="{escape(robot.root)}"/>',
            '    <origin xyz="0 0 0" rpy="0 0 0"/>',
            "  </joint>",
        ]
    for j in robot.joints:
        kind = j.type
        if kind == "revolute" and not (np.isfinite(j.lower) and np.isfinite(j.upper)):
            kind = "continuous"  # URDF revolute joints need limits
        lines += [
            f'  <joint name="{escape(j.name)}" type="{kind}">',
            f'    <parent link="{escape(j.parent)}"/>',
            f'    <child link="{escape(j.child)}"/>',
            f'    <origin xyz="{_v(j.xyz)}" rpy="{_v(j.rpy)}"/>',
        ]
        if kind != "fixed":
            lines.append(f'    <axis xyz="{_v(j.axis)}"/>')
        if kind in ("revolute", "prismatic"):
            effort = j.effort if np.isfinite(j.effort) else 1e6
            lines.append(
                f'    <limit lower="{_f(j.lower)}" upper="{_f(j.upper)}" '
                f'effort="{_f(effort)}" velocity="1e6"/>'
            )
        elif kind == "continuous" and np.isfinite(j.effort):
            lines.append(f'    <limit effort="{_f(j.effort)}" velocity="1e6"/>')
        if j.damping or j.friction:
            lines.append(f'    <dynamics damping="{_f(j.damping)}" friction="{_f(j.friction)}"/>')
        lines.append("  </joint>")
    lines.append("</robot>")
    path = out / f"{name}.urdf"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
