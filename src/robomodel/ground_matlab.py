"""MATLAB files for a ground robot (same equations as ground.py).

<name>_params.m (+ _low, _high)   parameter struct
robomodel_ground_dynamics.m      xdot = f(t, x, u, p), x = [x y psi u v r]
<name>_example.m                 ode15s run of a curving drive, compared with Python
<name>_reference.csv             the same run from the Python simulator
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from robomodel.ground import SLIP_ANGLE, SLIP_SPEED, GroundModel, model_range, simulate
from robomodel.matlab_export import _mat, matlab_name

EXAMPLE_TIME = 5.0  # s
EXAMPLE_DT = 0.05  # s

DYNAMICS = """function xdot = robomodel_ground_dynamics(~, x, u, p)
%ROBOMODEL_GROUND_DYNAMICS  Planar ground robot with wheel-ground contact (robomodel ground.py).
%   x = [x y psi u v r]' (position on the ground, heading, body velocities at the CG)
%   u = [drive commands (-1..1) of the driven wheels; steering angles (rad) of the steered]
u = u(:);
nd = p.n_drive;
cmd = max(min(u(1:nd), 1), -1);
delta = zeros(size(p.N));
if any(p.steer_in > 0)
    ang = max(min(u(nd + 1:end), p.max_steer(:)), -p.max_steer(:));
    delta(p.steer_in > 0) = ang(p.steer_in(p.steer_in > 0));
end
vx = x(4) - x(6) * p.xy(:, 2);
vy = x(5) + x(6) * p.xy(:, 1);
c = cos(delta); s = sin(delta);
vl = c .* vx + s .* vy;          % along the wheel
vt = -s .* vx + c .* vy;         % sideways
grip = p.mu * p.N;
fl = -p.crr * p.N .* tanh(vl / p.slip_speed);
d = p.drive_in > 0;
fl(d) = fl(d) + p.Fs(d) .* (cmd(p.drive_in(d)) - vl(d) ./ p.v0(d));
ft = -grip .* tanh(vt ./ (p.slip_speed + p.slip_angle * abs(vl)));
ft(p.caster) = 0;
tot = hypot(fl, ft);
k = ones(size(tot));
over = tot > grip;
k(over) = grip(over) ./ tot(over);   % friction circle
fl = fl .* k; ft = ft .* k;
fx = c .* fl - s .* ft;
fy = s .* fl + c .* ft;
mz = sum(p.xy(:, 1) .* fy - p.xy(:, 2) .* fx);
psi = x(3);
xdot = [x(4) * cos(psi) - x(5) * sin(psi);
        x(4) * sin(psi) + x(5) * cos(psi);
        x(6);
        sum(fx) / p.m + x(5) * x(6);
        sum(fy) / p.m - x(4) * x(6);
        mz / p.Iz];
end
"""


def example_inputs(gm: GroundModel) -> np.ndarray:
    """A curving drive: left side full, right side 60 % (or full drive with 0.2 rad steer)."""
    u = np.zeros(gm.n_inputs)
    n_drive = len(gm.driven_wheels)
    for j, i in enumerate(gm.driven_wheels):
        y = gm.vehicle.wheels[i].position[1]
        u[j] = 1.0 if (y <= 0 or gm.steered_wheels) else 0.6
    u[n_drive:] = 0.2
    return u


def _params(gm: GroundModel, fn: str, stamp: str) -> str:
    steer_max = [gm.vehicle.wheels[i].max_steer for i in gm.steered_wheels]
    return f"""function p = {fn}()
%{fn.upper()}  Ground robot '{gm.vehicle.name}' generated by robomodel ({gm.label}).
%   Planar model, contacts relative to the CG, body axes x forward, y right.
%   {stamp}
p.name = '{gm.vehicle.name}';
p.variant = '{gm.label}';
p.m = {gm.m:.17g};   % kg
p.Iz = {gm.izz:.17g};   % yaw inertia about the CG, kg m^2
p.cg_height = {gm.cg_height:.17g};   % m, for tip-over limits
p.xy = {_mat(gm.contact_xy)};   % contact points from the CG, m
p.N = {_mat(gm.normal.reshape(-1, 1))};   % normal loads at rest, N
p.Fs = {_mat(gm.stall_force.reshape(-1, 1))};   % drive force at full command, standstill, N
p.v0 = {_mat(np.where(gm.free_speed > 0, gm.free_speed, 1.0).reshape(-1, 1))};  % m/s, no load
p.drive_in = {_mat((gm.drive_input + 1).reshape(-1, 1))};   % index into u (0: not driven)
p.steer_in = {_mat((gm.steer_input + 1).reshape(-1, 1))};   % index into the steering angles
p.caster = logical({_mat(gm.caster.astype(float).reshape(-1, 1))});
p.max_steer = {_mat(np.array(steer_max).reshape(-1, 1)) if steer_max else "zeros(0, 1)"};   % rad
p.n_drive = {len(gm.driven_wheels)};
p.mu = {gm.mu:.17g};   % friction coefficient (surface: {gm.vehicle.surface[0]})
p.crr = {gm.rolling:.17g};   % rolling resistance coefficient
p.slip_speed = {SLIP_SPEED:.17g};   % m/s, friction smoothing near standstill
p.slip_angle = {SLIP_ANGLE:.17g};   % rad, side force near its peak at this slip angle
end
"""


def write_ground_matlab(gm: GroundModel, out_dir: str | Path) -> list[Path]:
    from robomodel.provenance import provenance

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    name = matlab_name(gm.vehicle.name)
    stamp = ", ".join(f"{k}={v}" for k, v in provenance(gm.vehicle).items() if "sha" not in k)
    written = []

    def write(filename: str, text: str) -> None:
        (out / filename).write_text(text, encoding="utf-8")
        written.append(out / filename)

    for label, variant in model_range(gm).items():
        suffix = "" if label == "nominal" else f"_{label}"
        write(f"{name}_params{suffix}.m", _params(variant, f"{name}_params{suffix}", stamp))
    write("robomodel_ground_dynamics.m", DYNAMICS)
    u = example_inputs(gm)
    traj = simulate(gm, EXAMPLE_TIME, u, dt_out=EXAMPLE_DT)
    csv = out / f"{name}_reference.csv"
    np.savetxt(
        csv,
        np.column_stack([traj.t, traj.state]),
        delimiter=",",
        header="t,x,y,psi,u,v,r",
        comments="",
        fmt="%.12g",
    )
    written.append(csv)
    write(
        f"{name}_example.m",
        f"""%{name.upper()}_EXAMPLE  Drive '{gm.vehicle.name}' on a curve, check against robomodel.
p = {name}_params();
u = {_mat(u.reshape(-1, 1))};   % [drive commands; steering angles]
x0 = zeros(6, 1);
opts = odeset('RelTol', 1e-8, 'AbsTol', 1e-10);   % friction is stiff near standstill: ode15s
times = 0:{EXAMPLE_DT:g}:{EXAMPLE_TIME:g};
[t, x] = ode15s(@(t, x) robomodel_ground_dynamics(t, x, u, p), times, x0, opts);
ref = readmatrix('{name}_reference.csv', 'NumHeaderLines', 1);
err = max(abs(x - ref(:, 2:7)), [], 'all');
fprintf('robomodel check: max difference MATLAB vs Python = %.3g\\n', err);
fprintf('final speed u = %.4f m/s, yaw rate r = %.4f rad/s\\n', x(end, 4), x(end, 6));
for v = {{'low', 'high'}}
    pv = feval(['{name}_params_' v{{1}}]);
    [~, xv] = ode15s(@(t, x) robomodel_ground_dynamics(t, x, u, pv), times, x0, opts);
    fprintf('%-7s model: final speed u = %.4f m/s\\n', v{{1}}, xv(end, 4));
end
figure('Name', p.name); plot(x(:, 2), x(:, 1)); axis equal; grid on;
xlabel('east y [m]'); ylabel('north x [m]'); title('path');
""",
    )
    return written
